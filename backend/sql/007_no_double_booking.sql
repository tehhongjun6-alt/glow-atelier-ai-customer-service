-- ============================================================
-- 防重复预约：由数据库保证"同一位美容师、同一段时间，只能有一笔有效预约"
--
-- 为什么不靠程序里的锁（threading.Lock）就好？
-- - 锁只在"一个后端程序"里有效。开两台服务器（或两个 worker），各有各的锁，
--   两位顾客同一瞬间订同一位美容师，两边都会检查通过、都写进去 → 重复预约
-- - 数据库只有一个，所有服务器都要经过它。规则写在数据库，谁都绕不过去
--
-- 为什么只管"美容师"就够了？
-- - 每笔新预约一定会分配一位美容师（booking/bookings.py 的 _pick_beautician）
-- - 店里 6 位美容师 < 同时最多 8 位顾客，所以美容师不重复 = 名额一定不会超过
-- - 淋浴间 2 间，身体去角质只有 2 位美容师会做，所以也不会超过
--
-- 旧资料：有 3 笔有效预约是"排班功能"做出来之前订的，没有美容师（NULL），
--         这条规则不会检查它们（NULL 不和任何人比较），不影响新预约。
-- ============================================================

-- exclude 约束要用到"等于（=）"和"时间重叠（&&）"一起比较，需要这个扩充功能
create extension if not exists btree_gist;

alter table public.bookings
  add constraint bookings_no_double_booking
  exclude using gist (
    beautician with =,                              -- 同一位美容师
    tstzrange(start_at, end_at, '[)') with &&       -- 时间有重叠（[) = 包含开始、不含结束，所以 15:00 结束、15:00 开始不算重叠）
  )
  where (status = 'confirmed');                     -- 只看有效的预约，已取消的不算

-- 撞到这条规则时，Postgres 回传错误代码 23P01（exclusion_violation），
-- 程序（booking/bookings.py）看到这个代码就重新排一位美容师，或告诉顾客"刚刚被订走了"。
